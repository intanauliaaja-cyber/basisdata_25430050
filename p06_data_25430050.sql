-- ============ PENYESUAIAN STOK ============

-- AB-09: stok bertambah sesuai qty pada faktur pembelian yang berstatus diterima
UPDATE barang b
JOIN (SELECT dp.id_barang, SUM(dp.qty_detail_pembelian) AS total_masuk
      FROM detail_pembelian dp
      JOIN pembelian p ON p.id_pembelian = dp.id_pembelian
      WHERE p.status_pembelian = 'diterima'
      GROUP BY dp.id_barang) m ON m.id_barang = b.id_barang
SET b.stok_barang = b.stok_barang + m.total_masuk
WHERE b.id_barang > 0;

-- Stok berkurang sesuai total qty pada seluruh detail pesanan (AB-04: hasilnya tidak boleh negatif)
UPDATE barang b
JOIN (SELECT id_barang, SUM(qty_detail_pesanan) AS total_keluar
      FROM detail_pesanan
      GROUP BY id_barang) k ON k.id_barang = b.id_barang
SET b.stok_barang = b.stok_barang - k.total_keluar
WHERE b.id_barang > 0;
